import assert from 'node:assert/strict';
import pg from 'pg';
import { saveCatalogueEvidence, recordReviewDecision, readReviewDecisions, needsAttention } from '../src/lib/victron-catalogue-review.mjs';
import { refreshReview } from '../src/lib/victron-catalogue-service.mjs';
if (!process.env.DATABASE_URL?.endsWith('/victron_review_test')) throw new Error('Requires isolated victron_review_test database');
const pool = new pg.Pool({connectionString:process.env.DATABASE_URL});
try {
  await pool.query('DROP TABLE IF EXISTS victron_catalogue_evidence,victron_catalogue_review,victron_catalogue_events,victron_sku_successions');
  await pool.query('CREATE TABLE victron_sku_successions(predecessor_sku text,successor_sku text)');
  await pool.query("INSERT INTO victron_sku_successions VALUES('PMP482305010','PMP482305012')");
  const observedAt=new Date().toISOString();
  const product={sku:'PMP482305012',description:'Victron MultiPlus',currency:'ZAR',price:525,enduser_price_zar:{price:1000}};
  await saveCatalogueEvidence(pool,[product],observedAt);
  const request=async company=>Response.json({Items:[],_hub:{complete:true,company,snapshot:'1',observed_at:observedAt}});
  const first=await refreshReview(pool,request); assert.equal(first.rows.length,2);
  await pool.query('UPDATE victron_catalogue_review SET acknowledged_signature=signature');
  await refreshReview(pool,request);
  let state=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0];
  assert.equal(state.signature,state.acknowledged_signature);
  await assert.rejects(()=>refreshReview(pool,async()=>Response.json({error:'unavailable'},{status:503})),/unavailable/);
  state=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0];
  assert.equal(state.rows.length,2); assert.ok(state.error); assert.notEqual(state.signature,state.acknowledged_signature);
  await assert.rejects(()=>saveCatalogueEvidence(pool,[],observedAt),/Incomplete/);
  await refreshReview(pool,request); state=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0]; assert.equal(state.error,null);
  const candidate={...product,description:'120V inverter',all_stock_by_warehouse:{af_sa_inzuzo:2}};
  await saveCatalogueEvidence(pool,[candidate],observedAt);
  await refreshReview(pool,request);
  await pool.query('UPDATE victron_catalogue_review SET acknowledged_signature=signature');
  const acknowledged=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0];
  await saveCatalogueEvidence(pool,[{...candidate,all_stock_by_warehouse:{af_sa_inzuzo:3}}],observedAt);
  await refreshReview(pool,request);
  state=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0];
  assert.equal(state.signature,acknowledged.signature);
  assert.equal(state.signature,state.acknowledged_signature,'positive quantity churn retains acknowledgement');
  await saveCatalogueEvidence(pool,[{...candidate,all_stock_by_warehouse:{af_sa_inzuzo:0}}],observedAt);
  await refreshReview(pool,request);
  state=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0];
  assert.equal(state.rows.length,2,'silenced rows remain visible');
  assert.ok(state.rows.every(row=>row.zaStock===0));
  assert.equal(state.acknowledged_signature,null,'a changed queue ends the old acknowledgement');
  await saveCatalogueEvidence(pool,[candidate],observedAt);
  await refreshReview(pool,request);
  state=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0];
  assert.equal(state.signature,acknowledged.signature,'the same SKU has returned');
  assert.notEqual(state.signature,state.acknowledged_signature,'a returning candidate alerts again');
  const thanda=state.rows.find(row=>row.company==='thanda-solar');
  await recordReviewDecision(pool,'operator',thanda,'review-ignored');
  await refreshReview(pool,request);
  state=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0];
  const ignored=state.rows.find(row=>row.company==='thanda-solar');
  assert.equal(ignored.fingerprint,thanda.fingerprint);
  assert.equal(needsAttention(ignored),false);
  assert.ok(Math.abs(Date.parse(ignored.ignoredUntil)-Date.now()-90*86400000)<5000,'database time defines the 90-day deadline');
  assert.equal(needsAttention(state.rows.find(row=>row.company==='sensible-solar')),true,'the other company is not ignored');
  await refreshReview(pool,request);
  assert.equal(needsAttention((await pool.query('SELECT * FROM victron_catalogue_review')).rows[0].rows.find(row=>row.company==='thanda-solar')),false,'ignore survives later comparisons');
  await recordReviewDecision(pool,'operator',ignored,'review-resumed');
  await refreshReview(pool,request);
  state=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0];
  assert.equal(needsAttention(state.rows.find(row=>row.company==='thanda-solar')),true,'undo overrides the latest ignore');
  await recordReviewDecision(pool,'operator',thanda,'review-ignored');
  await pool.query("UPDATE victron_catalogue_events SET created_at=now()-interval '91 days' WHERE action='review-ignored'");
  await refreshReview(pool,request);
  state=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0];
  assert.equal(needsAttention(state.rows.find(row=>row.company==='thanda-solar')),true,'expiry returns the candidate');
  await recordReviewDecision(pool,'operator',thanda,'review-approved');
  await refreshReview(pool,request);
  state=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0];
  assert.equal(state.rows.find(row=>row.company==='thanda-solar').kind,'new');
  assert.equal(state.rows.find(row=>row.company==='sensible-solar').kind,'review');
  const decisions=await readReviewDecisions(pool);
  assert.equal(decisions.find(row=>row.company==='thanda-solar').approvedReason,thanda.approvalReason,'approval and ignore histories remain independent');
  await saveCatalogueEvidence(pool,[{...candidate,price:0}],observedAt);
  await refreshReview(pool,request);
  state=(await pool.query('SELECT * FROM victron_catalogue_review')).rows[0];
  assert.equal(state.rows.find(row=>row.company==='thanda-solar').reviewAction,null,'accepted voltage does not waive malformed prices');
  console.log('Store integration passed: snapshots, recovery, stock-return alerts, scoped 90-day ignores, undo and advisory acceptance.');
} finally { await pool.end(); }
